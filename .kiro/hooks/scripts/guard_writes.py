"""PreToolUse guard for Kiro hooks.

Reads the hook event JSON from stdin. If the agent is about to write to a
protected path, prints the reason to stderr and exits with code 2 (block).
Fails open (exit 0) if the payload cannot be parsed, so a schema change in
Kiro never freezes the agent.
"""
from __future__ import annotations

import json
import os
import re
import sys

PROTECTED = [
    (r"(^|/)data/raw(/|$)", "data/raw is read-only source data"),
    (r"(^|/)\.env(\.|$)", "environment/secret file"),
    (r"(^|/)[^/]*(secret|credential)[^/]*$", "secret-like file name"),
    (r"\.(pem|key|p12)$", "key material"),
    (r"(^|/)\.kiro/steering/data-contracts\.md$", "contracts are edited by humans only"),
    (r"(^|/)\.kiro/specs/[^/]+/(requirements|design)\.md$", "spec requirements/design are edited by humans only"),
    (r"(^|/)tests/parity/vectors\.json$", "golden vectors are generated by `make parity`, never hand-edited"),
]

PATH_KEYS = {"path", "file_path", "filePath", "target", "target_file", "destination", "paths", "files"}


def candidate_paths(obj) -> list[str]:
    found: list[str] = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            if key in PATH_KEYS:
                if isinstance(value, str):
                    found.append(value)
                elif isinstance(value, list):
                    found.extend(v for v in value if isinstance(v, str))
            found.extend(candidate_paths(value))
    elif isinstance(obj, list):
        for item in obj:
            found.extend(candidate_paths(item))
    return found


def main() -> int:
    if os.environ.get("DOPPELGRUND_ALLOW_PROTECTED") == "1":
        return 0
    try:
        event = json.load(sys.stdin)
    except Exception as exc:  # fail open
        print(f"guard_writes: could not parse hook payload ({exc}); allowing.", file=sys.stderr)
        return 0
    cwd = event.get("cwd") or os.getcwd()
    for raw in set(candidate_paths(event.get("tool_input", {}))):
        rel = os.path.relpath(os.path.abspath(os.path.join(cwd, raw)), cwd).replace(os.sep, "/")
        for pattern, reason in PROTECTED:
            if re.search(pattern, rel):
                print(f"Blocked write to '{rel}': {reason}. Ask a human or see agent-rules.md.", file=sys.stderr)
                return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
